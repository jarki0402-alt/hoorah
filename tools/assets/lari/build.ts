/**
 * Build the Lari Terus asset packs into apps/web/public/models/lari/ and write the manifest the
 * game imports (file names with content hashes, so browsers fetch a regenerated pack).
 *
 *   npx tsx tools/assets/lari/build.ts            every pack
 *   npx tsx tools/assets/lari/build.ts runners    only the named packs (others keep their files)
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Glb } from '../src/gltf';
import { writeCity } from './city';
import { writeProps } from './props';
import { writeRunners } from './runners';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../../..');
const OUT = join(ROOT, 'apps/web/public/models/lari');
const MANIFEST = join(ROOT, 'apps/web/src/games/lari/asset-manifest.ts');

type Pack = 'runners' | 'props' | 'city';
const PACKS: readonly Pack[] = ['runners', 'props', 'city'];

interface Row {
  name: string;
  tris: number;
}

function build(pack: Pack): { bytes: Uint8Array; rows: Row[] } {
  const glb = new Glb();
  const rows: Row[] = [];
  const log = (r: Row) => {
    rows.push(r);
    process.stdout.write(`  ${pack}: ${r.name.padEnd(28)} ${String(r.tris).padStart(6)} tris\n`);
  };
  if (pack === 'runners') writeRunners(glb, log);
  else if (pack === 'props') writeProps(glb, log);
  else writeCity(glb, log);
  return { bytes: glb.toBuffer(), rows };
}

function main(): void {
  const want = process.argv.slice(2).filter((a): a is Pack => (PACKS as readonly string[]).includes(a));
  const todo = want.length ? want : PACKS;
  mkdirSync(OUT, { recursive: true });
  for (const pack of todo) {
    const t0 = performance.now();
    const { bytes, rows } = build(pack);
    writeFileSync(join(OUT, `${pack}.glb`), bytes);
    const tris = rows.reduce((s, r) => s + r.tris, 0);
    const secs = ((performance.now() - t0) / 1000).toFixed(1);
    process.stdout.write(
      `${pack}.glb: ${(bytes.byteLength / 1024).toFixed(0)} KB, ${tris} tris in all, ${secs} s\n`,
    );
  }
  const files: Record<string, string> = {};
  let total = 0;
  for (const pack of PACKS) {
    const path = join(OUT, `${pack}.glb`);
    if (!existsSync(path)) throw new Error(`missing ${path}: build it first`);
    const bytes = readFileSync(path);
    total += bytes.byteLength;
    const hash = createHash('sha256').update(bytes).digest('hex').slice(0, 10);
    files[pack] = `/models/lari/${pack}.glb?v=${hash}`;
  }
  const entries = PACKS.map((p) => `  ${p}: '${files[p]}',`).join('\n');
  const src = `/**
 * Generated by tools/assets/lari/build.ts: do not edit. Asset packs for Lari Terus (main screen
 * only), versioned by content hash.
 */
export const LARI_PACKS = {
${entries}
} as const;

/** Total size of the packs on disk (bytes). */
export const LARI_PACK_BYTES = ${total};
`;
  writeFileSync(MANIFEST, src);
  process.stdout.write(`all packs: ${(total / 1024 / 1024).toFixed(2)} MB\n`);
}

main();
